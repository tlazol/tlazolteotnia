export type IconName = keyof typeof icons

export function PixelIcon({ name, size = 18 }: { name: IconName; size?: number }) {
  const rows = icons[name]
  const main: string[] = []
  const accent: string[] = []
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') main.push(`M${x} ${y}h1v1h-1z`)
      else if (row[x] === '+') accent.push(`M${x} ${y}h1v1h-1z`)
    }
  })
  return (
    <svg
      className="pixel-icon"
      viewBox="0 0 12 12"
      width={size}
      height={size}
      aria-hidden="true"
      shapeRendering="crispEdges"
    >
      <path d={main.join('')} fill="currentColor" />
      {accent.length > 0 && <path d={accent.join('')} fill="var(--icon-accent, currentColor)" />}
    </svg>
  )
}
